// Standalone Node runner with Vite-compatible extension/directory and CJS resolution.
import assert from 'node:assert/strict'
import { registerHooks, createRequire } from 'node:module'
const lzPath=createRequire(import.meta.url).resolve('lz-string')
const bridge='data:text/javascript,'+encodeURIComponent(`import { createRequire } from 'node:module';const lz=createRequire(${JSON.stringify(import.meta.url)})(${JSON.stringify(lzPath)});export const {compressToUTF16,decompressFromUTF16}=lz;`)
registerHooks({resolve(specifier,context,next){if(specifier==='lz-string')return{url:bridge,shortCircuit:true};try{return next(specifier,context)}catch(e){if(e.code==='ERR_UNSUPPORTED_DIR_IMPORT')return next(`${specifier}/index.js`,context);if(e.code==='ERR_MODULE_NOT_FOUND'&&specifier.startsWith('.')&&!specifier.endsWith('.js'))return next(`${specifier}.js`,context);throw e}}})
globalThis.localStorage={data:{},getItem(k){return this.data[k]??null},setItem(k,v){this.data[k]=String(v)},removeItem(k){delete this.data[k]}}
const {DOMESTIC_COUNTRIES,DOMESTIC_LEAGUES,normalizeWorldConfig,setCountryDepth}=await import('../src/data/domesticLeagues.js')
const {focusedLimit,changeFocusedRole}=await import('../src/data/focusedWorld.js')
const {buildDomesticWorldTemplate,createDomesticSeason}=await import('../src/career/domesticWorld.js')
const {applyPendingSimulationScope,focusManagerLeague,syncSimulationScope,updateCupAttention}=await import('../src/career/simulationScope.js')
const {simulateFixtureMatch,applyMatchResultToLeague}=await import('../src/league/leagueEngine.js')
const {applyDailyDevelopment}=await import('../src/career/playerDevelopment.js')
let config=normalizeWorldConfig({simulationModel:'focused',mainCountryId:'pl',additionalCountryIds:['au','be','gb','jp'],international:{nationals:false,europe:false,paucc:false,aoucc:false,wucc:false}})
assert.equal(focusedLimit(config),4)
assert.equal(new Set(DOMESTIC_LEAGUES.filter(l=>config.leagues[l.id]==='playable').map(l=>l.countryId)).size,5)
assert.equal(changeFocusedRole(config,'ca','active',DOMESTIC_COUNTRIES),config)
assert.equal(changeFocusedRole(config,'fr','active',DOMESTIC_COUNTRIES),config)
const france=normalizeWorldConfig({...config,mainCountryId:'fr'})
assert.equal(focusedLimit(france),3);assert.equal(france.additionalCountryIds.length,3)
config=setCountryDepth(config,'au',1)
assert.equal(config.leagues['au-1'],'playable');assert.equal(config.leagues['au-2'],'background')
const template=buildDomesticWorldTemplate(config,2026,12345)
assert.equal(template.teams.length,DOMESTIC_LEAGUES.reduce((n,l)=>n+l.teams.length,0))
assert(template.teams.every(t=>t.players.length>=24))
const world={teamsById:Object.fromEntries(template.teams.map(t=>[t.id,t])),worldConfig:template.worldConfig}
const player=template.teams.find(t=>t.domesticLeagueId==='pl-1')
const league=createDomesticSeason(world,player.id,2026,12345)
assert.equal(league.otherLeagues.length+1,DOMESTIC_LEAGUES.length)
const background=league.otherLeagues.find(l=>l.countryId==='cn')
background.teamsById=world.teamsById
assert.equal(background.mode,'background')
const club=world.teamsById[background.teamIds[0]]
assert.equal(club.simulationMode,'off');assert(club.backgroundSimulation)
const fixture=background.fixtures.find(f=>f.competition==='league')
const fatigueBefore=club.players.map(p=>p.matchStamina??100)
const result=simulateFixtureMatch(background,fixture)
assert(result.simplified)
for(const [id,score] of [[fixture.homeTeamId,result.homeScore],[fixture.awayTeamId,result.awayScore]]) {
  assert.equal(result.boxScore.filter(r=>r.teamId===id).reduce((n,r)=>n+r.goals,0),score)
  assert.equal(result.boxScore.filter(r=>r.teamId===id).reduce((n,r)=>n+r.assists,0),score)
}
applyMatchResultToLeague(background,result)
assert.equal(fixture.status,'completed')
const playingClub=world.teamsById[fixture.homeTeamId]
assert(playingClub.players.some(p=>(p.developmentFatigue??0)>0))
league.internationalClubCups={editions:[{phase:'groups',fixtures:[{homeTeamId:playingClub.id,awayTeamId:player.id,date:'2026-09-09',status:'scheduled'}]}]}
const prior=playingClub.players.map(p=>[p.id,p.matchStamina,p.developmentFatigue])
updateCupAttention(league,'2026-09-03')
assert(playingClub.detailedCupAttention)
assert.deepEqual(playingClub.players.map(p=>[p.id,p.matchStamina,p.developmentFatigue]),prior)
assert.equal(playingClub.simulationMode,'off','Cup attention must not unlock transfer access')
const {buildTransferRowForPlayer,negotiateTransfer}=await import('../src/career/transfers/transferEngine.js')
assert.equal(buildTransferRowForPlayer(world,player.id,playingClub.players[0].id),null)
assert.equal(negotiateTransfer({world,playerTeamId:player.id,seasonYear:2026,league:{currentDate:'2026-08-20'}},{playerId:playingClub.players[0].id,offerAmount:1000}).error,'league_disabled')
league.internationalClubCups.editions[0].phase='complete'
updateCupAttention(league,'2026-09-10')
assert(!playingClub.detailedCupAttention)
applyDailyDevelopment(league,{date:'2026-09-11'})
assert(playingClub.players.every(p=>p.workload.lastRecoveryDate==='2026-09-11'))
const identities=template.teams.map(t=>[t.id,t.players.map(p=>p.id)])
focusManagerLeague(world,template.teams.find(t=>t.domesticLeagueId==='au-1').id)
syncSimulationScope(world,league)
assert.equal(world.worldConfig.mainCountryId,'au')
assert(world.worldConfig.additionalCountryIds.includes('pl'))
assert.deepEqual(template.teams.map(t=>[t.id,t.players.map(p=>p.id)]),identities)
assert.equal(fatigueBefore.length,club.players.length)
console.log('Focused world: 1+4 / France 1+3, all background leagues and rosters, quick scores/load, cup attention without access escalation, recovery and manager league switch passed.')

world.pendingSimulationConfig=normalizeWorldConfig({...world.worldConfig,additionalCountryIds:['ca']})
const nextPlayer=template.teams.find(t=>t.domesticLeagueId==='au-1')
assert.equal(world.worldConfig.additionalCountryIds.includes('ca'),false)
assert(applyPendingSimulationScope(world,nextPlayer.id))
assert.deepEqual(world.worldConfig.additionalCountryIds,['ca'])
assert.equal(world.worldConfig.leagues['ca-1'],'playable')
assert.equal(world.worldConfig.leagues['gb-1'],'background')
assert(!world.pendingSimulationConfig)
assert.deepEqual(template.teams.map(t=>[t.id,t.players.map(p=>p.id)]),identities)
console.log('Background transfer guards during cup participation and deferred scope changes passed.')
const {createCareer}=await import('../src/career/careerModel.js')
const actual=createCareer(0,{competition:'domestic',seasonYear:2026,playerTeamId:player.id,managerName:'Focused QA',worldConfig:normalizeWorldConfig({...config,additionalCountryIds:[],international:{nationals:true,europe:false,paucc:false,aoucc:false,wucc:false}})})
assert.equal(actual.league.otherLeagues.length+1,DOMESTIC_LEAGUES.length)
assert.equal(actual.world.worldConfig.international.nationals,true)
assert(actual.world.nationalPlayerPools)
assert(Object.values(actual.world.teamsById).some(t=>t.backgroundSimulation&&t.simulationMode==='off'))
assert(actual.world.managersById)
console.log('Actual focused career creation with national teams and persistent background clubs passed.')
